"""Turn an integer model file (.npz) into what the RTL reads: a parameter header and three memory images"""


import argparse
from pathlib import Path

import numpy as np

from intref import load

ROOT = Path(__file__).resolve().parent.parent
N_CLASSES = 8
IN_SHAPE = (2, 56, 56)   # two count planes (on-wafer dies, failed dies), 56 x 56

# Bit widths the RTL datapath is built with. The exporter refuses models that break them.
ACC_BITS = 32      # conv accumulator (signed)
M_BITS = 16        # requant multiplier (unsigned field)
S_MAX = 47         # requant shift field holds 1..S_MAX


def bits_u(v):
    return max(1, int(v).bit_length())


def clog2(n):
    return max(1, int(n - 1).bit_length())


def geometry(layers, in_c, in_h, in_w):
    geo, c, h, w = [], in_c, in_h, in_w
    wbase = pbase = 0
    for i, L in enumerate(layers):
        o, ci = L['w'].shape[:2]
        assert ci == c, f'layer {i}: expects {ci} input channels, previous layer gives {c}'
        assert L['w'].shape[2:] == (3, 3)
        pool = int(L['pool'])
        ph, pw = (h // 2, w // 2) if pool else (h, w)
        assert ph >= 1 and pw >= 1, f'layer {i}: map vanishes'
        geo.append(dict(C=c, O=o, H=h, W=w, HW=h * w, PH=ph, PW=pw, PHW=ph * pw, POOL=pool, K=c * 9,
                        WBASE=wbase, PBASE=pbase, OUTSZ=o * ph * pw, INSZ=c * h * w))
        wbase += o * c * 9
        pbase += o
        c, h, w = o, ph, pw
    return geo


def check_params(layers, head):
    for i, L in enumerate(layers):
        w, b, m, s = L['w'], L['b'], L['M'], L['S']
        assert w.min() >= -128 and w.max() <= 127, f'l{i}_w not int8'
        assert b.min() >= -2 ** (ACC_BITS - 1) and b.max() < 2 ** (ACC_BITS - 1), f'l{i}_b exceeds int32'
        assert m.min() >= 0 and m.max() < 2 ** M_BITS, f'l{i}_M must fit unsigned {M_BITS} bits'
        assert s.min() >= 1 and s.max() <= S_MAX, f'l{i}_S must be in 1..{S_MAX}'
    assert head['w'].shape[0] == N_CLASSES
    assert head['w'].min() >= -128 and head['w'].max() <= 127
    assert head['b'].min() >= -2 ** 31 and head['b'].max() < 2 ** 31


def hexw(v, bits):
    return format(int(v) & ((1 << bits) - 1), f'0{(bits + 3) // 4}x')


def write_lines(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n')


def packed(name, vals, bits=32):
    """SystemVerilog packed localparam; element i is name[i*bits +: bits]."""
    body = ', '.join(f"{bits}'d{int(v)}" if v >= 0 else f"{bits}'h{hexw(v, bits)} /*{int(v)}*/" for v in reversed(vals))
    return f'localparam logic [{len(vals)}*{bits}-1:0] {name} = {{{body}}};'


def expected_cycles(geo):
    """Compute-phase clocks of rtl/cnn_core.sv for this geometry (data independent). Per layer 1 setup cycle;
    per output channel 3 parameter cycles + one cycle per MAC term + 11 drain cycles; head: 1 clear cycle, then
    per final channel P_LAST reads + 3 + 8 head terms + 3; 1 done cycle; +1 because the counter starts at 1."""
    macs = sum(g['O'] * g['PHW'] * (4 if g['POOL'] else 1) * g['K'] for g in geo)
    return (len(geo) + macs + 14 * sum(g['O'] for g in geo) + 1
            + geo[-1]['O'] * (geo[-1]['PHW'] + 14) + 1 + 1)


def write_params(gen, geo, layers, head, src):
    nl = len(geo)
    map_depth = max([geo[0]['INSZ']] + [g['OUTSZ'] for g in geo])
    w_depth = sum(g['O'] * g['K'] for g in geo)
    p_depth = sum(g['O'] for g in geo)
    c_last = geo[-1]['O']
    p_last = geo[-1]['PHW']
    h_depth = c_last * N_CLASSES
    dim_max = max(max(g['H'], g['W']) for g in geo)
    ch_max = max(max(g['C'], g['O']) for g in geo)
    L = {k: [g[k] for g in geo] for k in geo[0]}
    sv = [
        f'// GENERATED by tools/export_rtl.py from {src} -- do not edit.',
        '// Layer i reads ping-pong RAM (i%2) and writes RAM ((i+1)%2); maps are [c][y][x] row-major.',
        f'localparam int NL        = {nl};',
        f'localparam int LW        = {bits_u(nl)};      // layer index width',
        f'localparam int IN_C      = {geo[0]["C"]};',
        f'localparam int IN_H      = {geo[0]["H"]};',
        f'localparam int IN_W      = {geo[0]["W"]};',
        f'localparam int IN_BYTES  = {geo[0]["INSZ"]};',
        f'localparam int MAP_DEPTH = {map_depth};',
        f'localparam int MAP_AW    = {clog2(map_depth)};',
        f'localparam int WROM_DEPTH = {w_depth};',
        f'localparam int WROM_AW   = {clog2(w_depth)};',
        f'localparam int PROM_DEPTH = {p_depth};',
        f'localparam int PROM_AW   = {clog2(p_depth)};',
        f'localparam int HROM_DEPTH = {h_depth};',
        f'localparam int HROM_AW   = {clog2(h_depth)};',
        f'localparam int C_LAST    = {c_last};',
        f'localparam int P_LAST    = {p_last};   // pixels per channel of the final map',
        f'localparam int G_W       = {bits_u(255 * p_last)};   // width of a per-channel sum of the final map',
        f'localparam int DW        = {bits_u(dim_max) + 1};    // signed map coordinate width',
        f'localparam int CW        = {bits_u(ch_max)};    // channel counter width',
        f'localparam int KW        = {bits_u(max(g["K"] for g in geo))};    // C*9 counter width',
        'localparam int FW        = 32;   // field width of the packed layer tables below',
        packed('L_C', L['C']), packed('L_O', L['O']), packed('L_H', L['H']), packed('L_W', L['W']),
        packed('L_HW', L['HW']), packed('L_PH', L['PH']), packed('L_PW', L['PW']), packed('L_POOL', L['POOL']),
        packed('L_K', L['K']), packed('L_WBASE', L['WBASE']), packed('L_PBASE', L['PBASE']),
        packed('L_OUTSZ', L['OUTSZ']),
        packed('HEAD_B', [int(v) for v in head['b']]),
        '',
    ]
    (gen / 'cnn_params.svh').write_text('\n'.join(sv))
    write_lines(gen / 'wrom.hex', [hexw(v, 8) for Lr in layers for v in Lr['w'].reshape(-1)])
    write_lines(gen / 'prom.hex', [hexw((int(s) << 48) | ((int(m) & 0xFFFF) << 32) | (int(b) & 0xFFFFFFFF), 54)
                                   for Lr in layers for b, m, s in zip(Lr['b'], Lr['M'], Lr['S'])])
    write_lines(gen / 'hrom.hex', [hexw(v, 8) for v in head['w'].T.reshape(-1)])

    info = [f'source: {src}', f'layers: {nl}', 'i   C   O   H   W pool  PH  PW   K  WBASE PBASE  OUTSZ   MACs']
    macs = 0
    for i, g in enumerate(geo):
        n_mac = g['O'] * g['PHW'] * (4 if g['POOL'] else 1) * g['K']
        macs += n_mac
        info.append(f"{i} {g['C']:3d} {g['O']:3d} {g['H']:3d} {g['W']:3d} {g['POOL']:4d} {g['PH']:3d} {g['PW']:3d} "
                    f"{g['K']:3d} {g['WBASE']:6d} {g['PBASE']:5d} {g['OUTSZ']:6d} {n_mac:7d}")
    info += [f'multiply-accumulates per wafer: {macs}',
             f'compute clocks per wafer: {expected_cycles(geo)} ({expected_cycles(geo) / 27e6 * 1e3:.1f} ms at 27 MHz)',
             f'map RAM depth {map_depth} (x2), weight ROM {w_depth} B, param ROM {p_depth} x 54 b, head ROM {h_depth} B']
    write_lines(gen / 'model_info.txt', info)
    return macs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--npz', default=str(ROOT / 'model/wafer_cnn_int8.npz'))
    a = ap.parse_args()
    layers, head = load(a.npz)
    check_params(layers, head)
    geo = geometry(layers, *IN_SHAPE)
    macs = write_params(ROOT / 'rtl/gen', geo, layers, head, Path(a.npz).name)
    print(f'export_rtl: {len(geo)} layers, {macs} MACs/wafer, {expected_cycles(geo)} cycles -> rtl/gen/')


if __name__ == '__main__':
    main()
